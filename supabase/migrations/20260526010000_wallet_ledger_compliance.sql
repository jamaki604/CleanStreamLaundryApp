create or replace view public.wallet_balances
with (security_invoker = true) as
select
  wa.id as wallet_account_id,
  wa.user_id,
  wa.status,
  coalesce(sum(wle.paid_amount_cents), 0)::integer as paid_balance_cents,
  coalesce(sum(wle.promo_amount_cents), 0)::integer as promo_balance_cents,
  coalesce(sum(wle.amount_cents), 0)::integer as total_balance_cents
from public.wallet_accounts wa
left join public.wallet_ledger_entries wle
  on wle.wallet_account_id = wa.id
group by wa.id, wa.user_id, wa.status;

create or replace function public.is_admin_or_owner()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.roles in ('Admin'::"Roles", 'Owner'::"Roles")
  );
$$;

create or replace function public.get_or_create_wallet_account(target_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  wallet_id uuid;
begin
  if target_user_id is null then
    raise exception 'Missing user id';
  end if;

  select id into wallet_id
  from public.wallet_accounts
  where user_id = target_user_id;

  if wallet_id is null then
    insert into public.wallet_accounts(user_id)
    values (target_user_id)
    on conflict (user_id) do update
      set updated_at = now()
    returning id into wallet_id;
  end if;

  return wallet_id;
end;
$$;

create or replace function public.sync_profile_wallet_balance(wallet_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_user_id uuid;
  total_cents integer;
begin
  select user_id, total_balance_cents
    into target_user_id, total_cents
  from public.wallet_balances
  where wallet_account_id = wallet_id;

  if target_user_id is not null then
    update public.profiles
    set balance = coalesce(total_cents, 0)::numeric / 100.0
    where id = target_user_id;
  end if;
end;
$$;

create or replace function public.record_wallet_load_from_stripe(
  target_user_id uuid,
  amount_cents integer,
  stripe_payment_intent_id text default null,
  stripe_checkout_session_id text default null,
  stripe_charge_id text default null,
  stripe_event_id text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  wallet_id uuid;
  load_id bigint;
  existing_wallet_id uuid;
  reward_before_cents integer;
  combined_cents integer;
  bonus_count integer;
  bonus_cents integer;
  remainder_cents integer;
begin
  if target_user_id is null or amount_cents is null or amount_cents <= 0 then
    raise exception 'Invalid wallet load';
  end if;

  select wl.wallet_account_id into existing_wallet_id
  from public.wallet_loads wl
  where (stripe_payment_intent_id is not null and wl.stripe_payment_intent_id = record_wallet_load_from_stripe.stripe_payment_intent_id)
     or (stripe_checkout_session_id is not null and wl.stripe_checkout_session_id = record_wallet_load_from_stripe.stripe_checkout_session_id)
     or (stripe_event_id is not null and wl.stripe_event_id = record_wallet_load_from_stripe.stripe_event_id)
  limit 1;

  if existing_wallet_id is not null then
    return existing_wallet_id;
  end if;

  wallet_id := public.get_or_create_wallet_account(target_user_id);

  select coalesce(round(reward_tracker * 100), 0)::integer
    into reward_before_cents
  from public.profiles
  where id = target_user_id;

  combined_cents := coalesce(reward_before_cents, 0) + amount_cents;
  bonus_count := combined_cents / 2000;
  bonus_cents := bonus_count * 500;
  remainder_cents := combined_cents % 2000;

  insert into public.wallet_loads(
    wallet_account_id,
    user_id,
    amount_cents,
    paid_amount_cents,
    promo_amount_cents,
    stripe_payment_intent_id,
    stripe_checkout_session_id,
    stripe_charge_id,
    stripe_event_id,
    status,
    note
  )
  values (
    wallet_id,
    target_user_id,
    amount_cents,
    amount_cents,
    bonus_cents,
    stripe_payment_intent_id,
    stripe_checkout_session_id,
    stripe_charge_id,
    stripe_event_id,
    'succeeded',
    'Stripe wallet load'
  )
  returning id into load_id;

  insert into public.wallet_ledger_entries(
    wallet_account_id,
    entry_type,
    amount_cents,
    paid_amount_cents,
    promo_amount_cents,
    wallet_load_id,
    stripe_payment_intent_id,
    stripe_charge_id,
    note
  )
  values (
    wallet_id,
    'load_paid',
    amount_cents,
    amount_cents,
    0,
    load_id,
    stripe_payment_intent_id,
    stripe_charge_id,
    'Paid loyalty card load'
  );

  if bonus_cents > 0 then
    insert into public.wallet_ledger_entries(
      wallet_account_id,
      entry_type,
      amount_cents,
      paid_amount_cents,
      promo_amount_cents,
      wallet_load_id,
      stripe_payment_intent_id,
      stripe_charge_id,
      note
    )
    values (
      wallet_id,
      'load_bonus',
      bonus_cents,
      0,
      bonus_cents,
      load_id,
      stripe_payment_intent_id,
      stripe_charge_id,
      'Promotional loyalty reward credit'
    );
  end if;

  update public.profiles
  set reward_tracker = remainder_cents::numeric / 100.0
  where id = target_user_id;

  perform public.sync_profile_wallet_balance(wallet_id);

  return wallet_id;
end;
$$;

create or replace function public.redeem_wallet_for_machine(
  target_user_id uuid,
  target_machine_id bigint,
  amount_cents integer,
  redemption_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  wallet_id uuid;
  paid_balance integer;
  promo_balance integer;
  promo_debit integer;
  paid_debit integer;
  redemption_id bigint;
begin
  if target_user_id is null or auth.uid() <> target_user_id then
    raise exception 'Unauthorized';
  end if;

  if amount_cents is null or amount_cents <= 0 then
    raise exception 'Invalid amount';
  end if;

  wallet_id := public.get_or_create_wallet_account(target_user_id);

  select paid_balance_cents, promo_balance_cents
    into paid_balance, promo_balance
  from public.wallet_balances
  where wallet_account_id = wallet_id;

  if coalesce(paid_balance, 0) + coalesce(promo_balance, 0) < amount_cents then
    raise exception 'Insufficient balance';
  end if;

  promo_debit := least(coalesce(promo_balance, 0), amount_cents);
  paid_debit := amount_cents - promo_debit;

  insert into public.wallet_redemptions(
    wallet_account_id,
    user_id,
    machine_id,
    amount_cents,
    paid_amount_cents,
    promo_amount_cents,
    status,
    note
  )
  values (
    wallet_id,
    target_user_id,
    target_machine_id,
    amount_cents,
    paid_debit,
    promo_debit,
    'succeeded',
    redemption_note
  )
  returning id into redemption_id;

  if promo_debit > 0 then
    insert into public.wallet_ledger_entries(
      wallet_account_id,
      entry_type,
      amount_cents,
      paid_amount_cents,
      promo_amount_cents,
      machine_id,
      note
    )
    values (
      wallet_id,
      'redeem_bonus',
      -promo_debit,
      0,
      -promo_debit,
      target_machine_id,
      redemption_note
    );
  end if;

  if paid_debit > 0 then
    insert into public.wallet_ledger_entries(
      wallet_account_id,
      entry_type,
      amount_cents,
      paid_amount_cents,
      promo_amount_cents,
      machine_id,
      note
    )
    values (
      wallet_id,
      'redeem_paid',
      -paid_debit,
      -paid_debit,
      0,
      target_machine_id,
      redemption_note
    );
  end if;

  perform public.sync_profile_wallet_balance(wallet_id);

  return jsonb_build_object(
    'wallet_account_id', wallet_id,
    'redemption_id', redemption_id,
    'paid_debit_cents', paid_debit,
    'promo_debit_cents', promo_debit
  );
end;
$$;

