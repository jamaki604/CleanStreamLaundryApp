create or replace function public.anonymize_wallet_for_deleted_user(
  target_user_id uuid,
  deletion_note text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  wallet_id uuid;
begin
  if target_user_id is null then
    raise exception 'Missing user id';
  end if;

  wallet_id := public.get_or_create_wallet_account(target_user_id);

  update public.wallet_accounts
  set
    user_id = null,
    status = 'deleted',
    deleted_at = now(),
    deletion_acknowledged_at = now(),
    deleted_reason = deletion_note,
    updated_at = now()
  where id = wallet_id;

  update public.wallet_loads
  set user_id = null
  where wallet_account_id = wallet_id;

  update public.wallet_redemptions
  set user_id = null
  where wallet_account_id = wallet_id;

  return wallet_id;
end;
$$;

-- Backfill existing profile balances as legacy paid wallet value.
insert into public.wallet_accounts(user_id)
select p.id
from public.profiles p
where not exists (
  select 1 from public.wallet_accounts wa where wa.user_id = p.id
);

insert into public.wallet_ledger_entries(
  wallet_account_id,
  entry_type,
  amount_cents,
  paid_amount_cents,
  promo_amount_cents,
  note
)
select
  wa.id,
  'legacy_balance',
  coalesce(round(p.balance * 100), 0)::integer,
  coalesce(round(p.balance * 100), 0)::integer,
  0,
  'Legacy profiles.balance backfill'
from public.profiles p
join public.wallet_accounts wa on wa.user_id = p.id
where coalesce(p.balance, 0) <> 0
  and not exists (
    select 1
    from public.wallet_ledger_entries wle
    where wle.wallet_account_id = wa.id
      and wle.entry_type = 'legacy_balance'
  );

