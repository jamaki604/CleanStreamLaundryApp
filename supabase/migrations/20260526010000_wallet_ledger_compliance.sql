-- Clean Stream wallet ledger and compliance foundation.
-- This migration is intentionally additive first: profiles.balance remains as a
-- compatibility cache while wallet_balances becomes the source of truth.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.wallet_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  status text not null default 'active'
    check (status in ('active', 'deleted', 'locked')),
  locked_at timestamptz,
  deleted_at timestamptz,
  deletion_acknowledged_at timestamptz,
  deleted_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_loads (
  id bigint generated by default as identity primary key,
  wallet_account_id uuid not null references public.wallet_accounts(id),
  user_id uuid references auth.users(id) on delete set null,
  amount_cents integer not null check (amount_cents > 0),
  paid_amount_cents integer not null check (paid_amount_cents >= 0),
  promo_amount_cents integer not null default 0 check (promo_amount_cents >= 0),
  stripe_payment_intent_id text unique,
  stripe_checkout_session_id text unique,
  stripe_charge_id text unique,
  stripe_event_id text unique,
  status text not null default 'succeeded'
    check (status in ('pending', 'succeeded', 'refunded', 'void')),
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.wallet_ledger_entries (
  id bigint generated by default as identity primary key,
  wallet_account_id uuid not null references public.wallet_accounts(id),
  entry_type text not null check (
    entry_type in (
      'legacy_balance',
      'load_paid',
      'load_bonus',
      'redeem_paid',
      'redeem_bonus',
      'admin_adjustment',
      'legal_cash_redemption',
      'stripe_refund',
      'void'
    )
  ),
  amount_cents integer not null,
  paid_amount_cents integer not null default 0,
  promo_amount_cents integer not null default 0,
  wallet_load_id bigint references public.wallet_loads(id),
  stripe_payment_intent_id text,
  stripe_charge_id text,
  stripe_refund_id text,
  machine_id bigint references public."Machines"(id) on delete set null,
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint wallet_ledger_amount_split_matches check (
    amount_cents = paid_amount_cents + promo_amount_cents
  )
);

create table if not exists public.wallet_redemptions (
  id bigint generated by default as identity primary key,
  wallet_account_id uuid not null references public.wallet_accounts(id),
  user_id uuid references auth.users(id) on delete set null,
  machine_id bigint references public."Machines"(id) on delete set null,
  amount_cents integer not null check (amount_cents > 0),
  paid_amount_cents integer not null default 0 check (paid_amount_cents >= 0),
  promo_amount_cents integer not null default 0 check (promo_amount_cents >= 0),
  status text not null default 'succeeded'
    check (status in ('succeeded', 'void')),
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.deleted_account_complaints (
  id bigint generated by default as identity primary key,
  wallet_account_id uuid not null references public.wallet_accounts(id),
  complaint_note text not null,
  resolution text not null default 'denied'
    check (resolution in ('denied', 'legal_cash_redemption', 'other_required_remedy')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

