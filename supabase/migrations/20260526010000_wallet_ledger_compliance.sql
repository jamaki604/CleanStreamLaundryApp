create or replace function public.update_user_balance()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.type = 'credit' then
    update public.profiles
    set balance = balance + new.amount
    where id = new.user_id;
  elsif new.type = 'debit' then
    update public.profiles
    set balance = balance - new.amount
    where id = new.user_id;
  end if;
  return new;
end;
$$;

