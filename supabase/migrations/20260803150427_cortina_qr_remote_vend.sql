create table public.washer_size_rates (
  id bigint generated by default as identity primary key,
  location_id bigint not null references public."Locations"(id) on delete cascade,
  size_label text not null check (btrim(size_label) <> ''),
  capacity_kg bigint not null check (capacity_kg > 0),
  price_cents integer not null check (price_cents > 0),
  is_active boolean not null default true,
  review_required boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint washer_size_rates_location_label_key unique (location_id, size_label)
);

alter table public."Machines"
  add column washer_size_rate_id bigint
  references public.washer_size_rates(id) on delete restrict;

create table public.cortina_machine_config (
  machine_id bigint primary key references public."Machines"(id) on delete cascade,
  public_machine_token uuid not null default gen_random_uuid() unique,
  nayax_terminal_id text,
  nayax_uniqr text,
  pulse_line_number integer check (pulse_line_number > 0),
  environment text not null default 'sandbox'
    check (environment in ('sandbox', 'production')),
  is_enabled boolean not null default false,
  review_required boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cortina_machine_identifier_required check (
    not is_enabled or (
      (nullif(btrim(nayax_terminal_id), '') is not null or
       nullif(btrim(nayax_uniqr), '') is not null)
      and pulse_line_number is not null
      and not review_required
    )
  )
);

