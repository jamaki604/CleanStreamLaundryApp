-- Preserve existing washer prices while moving each location/size/price
-- combination into a managed rate that must be reviewed before Cortina use.
with legacy_prices as (
  select distinct
    m."Location_ID" as location_id,
    m."Weight_kg" as capacity_kg,
    round(m."Price" * 100)::integer as price_cents
  from public."Machines" m
  where lower(coalesce(m."Machine_type", '')) = 'washer'
    and m."Location_ID" is not null
    and m."Weight_kg" is not null
    and m."Weight_kg" > 0
    and m."Price" is not null
    and m."Price" > 0
), legacy_price_counts as (
  select location_id, capacity_kg, count(*) as price_count
  from legacy_prices
  group by location_id, capacity_kg
)
insert into public.washer_size_rates (
  location_id,
  size_label,
  capacity_kg,
  price_cents,
  review_required
)
select
  legacy.location_id,
  case
    when counts.price_count = 1 then legacy.capacity_kg || ' kg'
    else legacy.capacity_kg || ' kg - legacy $' ||
      to_char(legacy.price_cents::numeric / 100, 'FM999999990.00')
  end,
  legacy.capacity_kg,
  legacy.price_cents,
  true
from legacy_prices legacy
join legacy_price_counts counts
  using (location_id, capacity_kg)
on conflict (location_id, size_label) do nothing;

update public."Machines" m
set washer_size_rate_id = rate.id
from public.washer_size_rates rate
where lower(coalesce(m."Machine_type", '')) = 'washer'
  and rate.location_id = m."Location_ID"
  and rate.capacity_kg = m."Weight_kg"
  and rate.price_cents = round(m."Price" * 100)::integer;

insert into public.cortina_machine_config(machine_id)
select id from public."Machines"
on conflict (machine_id) do nothing;

create or replace function public.apply_washer_size_rate_to_machine()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  selected_rate public.washer_size_rates%rowtype;
begin
  if lower(coalesce(new."Machine_type", '')) <> 'washer' then
    if new.washer_size_rate_id is not null then
      raise exception 'Only washers may use a washer size rate';
    end if;
    return new;
  end if;

  if new.washer_size_rate_id is null then
    return new;
  end if;

  select * into selected_rate
  from public.washer_size_rates
  where id = new.washer_size_rate_id;

  if not found or selected_rate.location_id is distinct from new."Location_ID" then
    raise exception 'Washer size rate must belong to the machine location';
  end if;

  if tg_op = 'INSERT' or new.washer_size_rate_id is distinct from old.washer_size_rate_id then
    if not selected_rate.is_active then
      raise exception 'Inactive washer size rate cannot be assigned';
    end if;
  end if;

  new."Weight_kg" := selected_rate.capacity_kg;
  new."Price" := selected_rate.price_cents::double precision / 100.0;
  return new;
end;
$$;

create trigger apply_washer_size_rate_to_machine
before insert or update of washer_size_rate_id, "Location_ID", "Machine_type", "Price", "Weight_kg"
on public."Machines"
for each row execute function public.apply_washer_size_rate_to_machine();

