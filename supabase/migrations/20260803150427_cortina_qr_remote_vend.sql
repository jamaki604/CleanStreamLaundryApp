create table public.cortina_vend_sessions (
  id uuid primary key default gen_random_uuid(),
  client_request_id uuid not null unique,
  client_access_token_hash text not null unique,
  machine_id bigint not null references public."Machines"(id) on delete restrict,
  user_id uuid references auth.users(id) on delete set null,
  washer_size_rate_id bigint references public.washer_size_rates(id) on delete set null,
  amount_cents integer not null check (amount_cents > 0),
  dryer_minutes integer check (dryer_minutes is null or dryer_minutes between 5 and 90),
  currency text not null default 'USD' check (currency ~ '^[A-Z]{3}$'),
  payment_method text not null check (payment_method in ('card', 'wallet')),
  channel text not null check (channel in ('app', 'web')),
  status text not null default 'payment_pending' check (
    status in (
      'payment_pending', 'paid', 'starting', 'awaiting_sale', 'approved',
      'started', 'voided', 'refunded', 'failed', 'timed_out',
      'support_required'
    )
  ),
  transaction_id text not null unique check (char_length(transaction_id) between 8 and 40),
  stripe_payment_intent_id text unique,
  stripe_checkout_session_id text unique,
  stripe_charge_id text,
  stripe_refund_id text,
  wallet_redemption_id bigint unique references public.wallet_redemptions(id),
  nayax_transaction_id text,
  nayax_rrn text,
  failure_code text,
  failure_message text,
  start_requested_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.cortina_vend_events (
