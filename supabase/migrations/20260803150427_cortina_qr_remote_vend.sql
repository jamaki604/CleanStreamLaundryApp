create or replace function public.reverse_cortina_wallet_redemption(
  target_session_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_session public.cortina_vend_sessions%rowtype;
  target_redemption public.wallet_redemptions%rowtype;
begin
  select * into target_session
  from public.cortina_vend_sessions
  where id = target_session_id
  for update;

  if not found or target_session.payment_method <> 'wallet' or
     target_session.wallet_redemption_id is null then
    raise exception 'Wallet vend session not found';
  end if;

  select * into target_redemption
  from public.wallet_redemptions
  where id = target_session.wallet_redemption_id
  for update;

  if target_redemption.status = 'void' then
    return false;
  end if;

  insert into public.wallet_ledger_entries (
    wallet_account_id,
    entry_type,
    amount_cents,
    paid_amount_cents,
    promo_amount_cents,
    machine_id,
    note
  ) values (
    target_redemption.wallet_account_id,
    'void',
    target_redemption.amount_cents,
    target_redemption.paid_amount_cents,
    target_redemption.promo_amount_cents,
    target_redemption.machine_id,
    'Cortina vend reversal for session ' || target_session_id
  );

  update public.wallet_redemptions
  set status = 'void'
  where id = target_redemption.id;

  perform public.sync_profile_wallet_balance(target_redemption.wallet_account_id);

  update public.cortina_vend_sessions
  set status = 'refunded', completed_at = now()
  where id = target_session_id;

  return true;
end;
$$;

revoke all on function public.reverse_cortina_wallet_redemption(uuid)
  from public, anon, authenticated;
grant execute on function public.reverse_cortina_wallet_redemption(uuid)
  to service_role;

create or replace function public.redeem_wallet_for_cortina(
  target_session_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_session public.cortina_vend_sessions%rowtype;
  redemption jsonb;
begin
  select * into target_session
  from public.cortina_vend_sessions
  where id = target_session_id
  for update;

  if not found or target_session.payment_method <> 'wallet' or
     target_session.status <> 'payment_pending' then
    raise exception 'Wallet vend session is not payable';
  end if;

  if target_session.user_id is null or
     target_session.user_id is distinct from (select auth.uid()) then
    raise exception 'Unauthorized';
  end if;

  redemption := public.redeem_wallet_for_machine(
    target_session.user_id,
    target_session.machine_id,
    target_session.amount_cents,
    'Cortina vend ' || target_session.id
  );

  update public.cortina_vend_sessions
  set
    status = 'paid',
    wallet_redemption_id = (redemption->>'redemption_id')::bigint
  where id = target_session.id;

  return redemption;
end;
$$;

revoke all on function public.redeem_wallet_for_cortina(uuid)
  from public, anon;
grant execute on function public.redeem_wallet_for_cortina(uuid)
  to authenticated;
